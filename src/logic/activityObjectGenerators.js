export function generateDragDropObjects(activity) {
  const baseObjects = removeAutoGeneratedObjects(activity);
  const draggables = activity.dragDropDraggables || [];
  const dropzones = activity.dragDropDropzones || [];

  const objects = [];
  const dragStartX = 80;
  const dragStartY = 60;
  const dropStartX = 400;
  const dropStartY = 60;
  const itemHeight = 48;
  const gap = 8;

  // Sürüklenebilir öğeler (sol)
  draggables.forEach((item, index) => {
    const y = dragStartY + index * (itemHeight + gap);
    objects.push({
      ...createCanvasShapeObject(
        item.label || item.text || '',
        dragStartX,
        y,
        240,
        itemHeight,
        ANSWER_LAYER_STYLE.draggable
      ),
      id: `auto-drag-${item.id || index}`,
      layerId: 'cevap',
      autoGenerated: true,
      type: 'draggable',
    });
  });

  // Bırakma alanları (sağ)
  dropzones.forEach((item, index) => {
    const y = dropStartY + index * (itemHeight + gap);
    objects.push({
      ...createCanvasShapeObject(
        item.label || item.text || '',
        dropStartX,
        y,
        240,
        itemHeight,
        ANSWER_LAYER_STYLE.dropzone
      ),
      id: `auto-drop-${item.id || index}`,
      layerId: 'cevap',
      autoGenerated: true,
      type: 'dropzone',
    });
  });

  return [...baseObjects, ...objects];
}

export function generateFillBlankObjects(activity) {
  const baseObjects = removeAutoGeneratedObjects(activity);
  const text = activity.fillBlankText || '';
  const answers = activity.fillBlankAnswers || [];
  const tx = runtimeText(activity);

  const objects = [];

  // Ana metin
  objects.push({
    ...createCanvasTextObject(text, 80, 60, 640, 200, {
      ...ANSWER_LAYER_STYLE.labelText,
      fontSize: 15,
      lineHeight: 2,
    }),
    id: 'auto-fb-text',
    layerId: 'cevap',
    autoGenerated: true,
  });

  // Boşluk input kutuları (basit olarak metin altına sıralanmış)
  answers.forEach((ans, index) => {
    const y = 280 + index * 44;
    objects.push({
      ...createCanvasShapeObject(
        ans.label || `${tx.blankLabel} ${index + 1}`,
        80,
        y,
        200,
        36,
        ANSWER_LAYER_STYLE.inputBox
      ),
      id: `auto-fb-input-${index}`,
      layerId: 'cevap',
      autoGenerated: true,
    });
  });

  return [...baseObjects, ...objects];
}

