export function generateSurveyObjects(activity) {
  const baseObjects = removeAutoGeneratedObjects(activity);
  const questions = activity.surveyQuestions || [];
  const tx = runtimeText(activity);
  if (!questions.length) return baseObjects;

  const objects = [];
  const startX = 80;
  const startY = 60;
  const cardWidth = 600;
  const questionHeight = 80;
  const gap = 16;

  questions.forEach((q, index) => {
    const y = startY + index * (questionHeight + gap);

    objects.push({
      ...createCanvasTextObject(
        `${index + 1}. ${q.question || ''}`,
        startX,
        y,
        cardWidth,
        36,
        ANSWER_LAYER_STYLE.labelText
      ),
      id: `auto-survey-q-${index}`,
      layerId: 'cevap',
      autoGenerated: true,
    });

    // Örnek cevap seçenekleri (evet/hayır veya 1-5)
    const options = q.options || [tx.yesLabel, tx.noLabel];
    options.forEach((opt, optIndex) => {
      objects.push({
        ...createCanvasButtonObject(
          opt,
          startX + optIndex * 100,
          y + 40,
          90,
          32,
          ANSWER_LAYER_STYLE.optionCard
        ),
        id: `auto-survey-opt-${index}-${optIndex}`,
        layerId: 'cevap',
        autoGenerated: true,
      });
    });
  });

  return [...baseObjects, ...objects];
}

/**
 * Tüm türler için ana jeneratör fonksiyonu.
 * activity.type'e göre doğru üreticiyi çağırır.
 * @param {object} activity
 * @returns {Array<object>}
 */
export function generateAnswerObjectsForActivity(activity) {
  if (!activity) return [];

  const type = activity.type;

  switch (type) {
    case 'selection':
      return generateSelectionObjects(activity);
    case 'true-false':
      return generateTrueFalseObjects(activity);
    case 'sequence':
      return generateSequenceObjects(activity);
    case 'matching':
      return generateMatchingObjects(activity);
    case 'drag-drop':
      return generateDragDropObjects(activity);
    case 'fill-blank':
      return generateFillBlankObjects(activity);
    case 'text-entry':
      return generateTextEntryObjects(activity);
    case 'numeric':
      return generateNumericObjects(activity);
    case 'survey':
      return generateSurveyObjects(activity);
    default:
      return activity.objects || [];
  }
}
