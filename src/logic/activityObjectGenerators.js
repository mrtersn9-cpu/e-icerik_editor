function removeAutoGeneratedObjects(activity) {
  const objects = activity.objects || [];
  // Yalnizca uretilmis nesneleri kaldir (autoGenerated veya answer-template).
  // Kullanicinin 'cevap' katmanina ELLE ekledigi nesneler (uretim damgasi yok)
  // korunur; eski hal tum 'cevap' katmanini silip elle emegi sessizce kaybediyordu.
  return objects.filter((obj) => !obj.autoGenerated && obj.generatedBy !== 'answer-template');
}

export function generateTrueFalseObjects(activity) {
  const baseObjects = removeAutoGeneratedObjects(activity);
  const options = activity.tfStatements || [];
  if (!options.length) return baseObjects;
  // Buton etiketleri etkinliğin üretim diline göre (Doğru/True/Richtig).
  const tx = runtimeText(activity);

  const objects = [];
  const startX = 80;
  const startY = 60;
  const cardWidth = 600;
  const cardHeight = 70;
  const gap = 12;

  options.forEach((opt, index) => {
    const y = startY + index * (cardHeight + gap);
    const cardId = `auto-tf-card-${index}`;
    const textId = `auto-tf-text-${index}`;
    const trueBtnId = `auto-tf-true-${index}`;
    const falseBtnId = `auto-tf-false-${index}`;

    // Kart arka planı
    objects.push({
      ...createCanvasShapeObject('', startX, y, cardWidth, cardHeight, ANSWER_LAYER_STYLE.card),
      id: cardId,
      layerId: 'cevap',
      autoGenerated: true,
    });

    // Numara + ifade metni
    objects.push({
      ...createCanvasTextObject(
        `${index + 1}. ${opt.statement || ''}`,
        startX + 16,
        y + 14,
        cardWidth - 220,
        40,
        ANSWER_LAYER_STYLE.labelText
      ),
      id: textId,
      layerId: 'cevap',
      autoGenerated: true,
    });

    // Doğru butonu
    objects.push({
      ...createCanvasButtonObject(
        tx.trueLabel,
        startX + cardWidth - 190,
        y + 16,
        80,
        38,
        ANSWER_LAYER_STYLE.trueBtn
      ),
      id: trueBtnId,
      layerId: 'cevap',
      autoGenerated: true,
    });

    // Yanlış butonu
    objects.push({
      ...createCanvasButtonObject(
        tx.falseLabel,
        startX + cardWidth - 100,
        y + 16,
        80,
        38,
        ANSWER_LAYER_STYLE.falseBtn
      ),
      id: falseBtnId,
      layerId: 'cevap',
      autoGenerated: true,
    });
  });

  return [...baseObjects, ...objects];
}

export function generateSelectionObjects(activity) {
  const baseObjects = removeAutoGeneratedObjects(activity);
  const question = activity.questionText || '';
  const options = activity.mcOptions || [];
  if (!options.length) return baseObjects;

  const objects = [];
  const startX = 80;
  const startY = 60;
  const cardWidth = 560;
  const optionHeight = 52;
  const gap = 8;

  // Soru metni
  objects.push({
    ...createCanvasTextObject(question, startX, startY, cardWidth, 36, {
      ...ANSWER_LAYER_STYLE.labelText,
      fontSize: 16,
      fontWeight: 700,
    }),
    id: 'auto-sel-question',
    layerId: 'cevap',
    autoGenerated: true,
  });

  // Seçenek kartları
  options.forEach((opt, index) => {
    const y = startY + 44 + index * (optionHeight + gap);
    const letter = String.fromCharCode(65 + index);
    const isCorrect = !!opt.isCorrect;

    objects.push({
      ...createCanvasShapeObject(
        `${letter}. ${opt.label || ''}`,
        startX,
        y,
        cardWidth,
        optionHeight,
        isCorrect ? ANSWER_LAYER_STYLE.optionCardCorrect : ANSWER_LAYER_STYLE.optionCard
      ),
      id: `auto-sel-opt-${index}`,
      layerId: 'cevap',
      autoGenerated: true,
    });
  });

  return [...baseObjects, ...objects];
}

